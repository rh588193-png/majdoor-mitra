    fun statusLabel(status: AttendanceStatus): String = when (status) {
        AttendanceStatus.PRESENT -> if (appName == "MAJDOOR MITRA" && workerRole == "मजदूर (Worker)") "उपस्थित (P)" else "Present (P)"
